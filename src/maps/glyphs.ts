/** 3×5 capitals */
const LATIN: Record<string, string[]> = {
  K: ['#.#', '##.', '#..', '##.', '#.#'],
  O: ['###', '#.#', '#.#', '#.#', '###'],
  B: ['##.', '#.#', '##.', '#.#', '##.'],
  A: ['.#.', '#.#', '###', '#.#', '#.#'],
  N: ['#.#', '###', '###', '###', '#.#'],
  P: ['##.', '#.#', '##.', '#..', '#..'],
};

function glyph(ch: string): string[] {
  const g = KANJI[ch] ?? LATIN[ch];
  if (!g) throw new Error(`no glyph for ${ch}`);
  return g;
}

/** width in voxels of `text` set with `gap` voxels between characters */
export function textWidth(text: string, gap = 2): number {
  let w = 0;
  for (const ch of text) w += glyph(ch)[0].length + gap;
  return Math.max(0, w - gap);
}

/** height in voxels of the tallest character of `text` */
export function textHeight(text: string): number {
  let h = 0;
  for (const ch of text) h = Math.max(h, glyph(ch).length);
  return h;
}

/**
 * Set `text` in voxels: `at(u, row)` maps a column u (0 = the first character's left edge, growing in reading order)
 * and a row (0 = the top) to the world voxel to fill with `mat`. Shorter characters sit on the baseline.
 */
export function stampText(b: Builder, text: string, mat: number, at: (u: number, row: number) => [number, number, number], gap = 2): void {
  const h = textHeight(text);
  let u0 = 0;
  for (const ch of text) {
    const g = glyph(ch);
    const drop = h - g.length;
    for (let r = 0; r < g.length; r++)
      for (let c = 0; c < g[r].length; c++) {
        if (g[r][c] !== '#') continue;
        const [x, y, z] = at(u0 + c, r + drop);
        b.set(x, y, z, mat);
      }
    u0 += g[0].length + gap;
  }
}
